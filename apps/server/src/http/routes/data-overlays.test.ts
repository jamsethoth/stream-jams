import Fastify from "fastify";
import { describe, expect, it } from "vitest";
import { DataOverlayService } from "@stream-jams/core";
import { createInMemoryStreamJamsDatabase } from "../../modules/db/database.js";
import { SqliteDataOverlayRepository } from "../../modules/data-overlays/sqlite-data-overlay-repository.js";
import { LocalManagementSessionService } from "../../modules/auth/management-session-service.js";
import { RuntimeMaintenanceGate } from "../../modules/backup/runtime-maintenance-gate.js";
import { createTestManagementSecurity, managementTestHeaders } from "../test-support/management-security-fixture.js";
import { registerDataOverlayRoutes } from "./data-overlays.js";
it("protects definitions and Operator commands with session/CSRF and returns current conflicts", async () => {
  const db = createInMemoryStreamJamsDatabase();
  let next = 0;
  const gate = new RuntimeMaintenanceGate();
  const service = new DataOverlayService(new SqliteDataOverlayRepository(db), { generateId: () => `id-${++next}`, now: () => "2026-10-08T00:00:00.000Z", runMutation: work => gate.runConfigurationMutation(work) });
  const sessions = new LocalManagementSessionService();
  const session = await sessions.createSession();
  const headers = managementTestHeaders(session,"POST");
  const app = Fastify();
  registerDataOverlayRoutes(app, { dataOverlayService: service, managementAuthPreHandler: createTestManagementSecurity(sessions), managementRateLimitPreHandler: (_req,_reply,done) => done() });
  expect((await app.inject({ url: "/data-overlays", headers: { authorization: "Bearer overlay-secret" } })).statusCode).toBe(401);
  expect((await app.inject({ method: "POST", url: "/data-overlays/values", headers: managementTestHeaders(session), payload: {} })).statusCode).toBe(403);
  const created = await app.inject({ method: "POST", url: "/data-overlays/values", headers, payload: { name: "Count", kind: "integer", resetDefault: 0, resetGroupId: null } });
  expect(created.statusCode,created.body).toBe(201);
  expect((await app.inject({ method: "POST", url: "/operator/data-overlays/values/id-1/add", headers, payload: { amount: 1 } })).statusCode).toBe(200);
  const conflict = await app.inject({ method: "POST", url: "/operator/data-overlays/values/id-1/set", headers, payload: { content: 50, expectedRevision: 0 } });
  expect(conflict.statusCode).toBe(409);
  expect(conflict.json().error.currentValue.content).toBe(1);
  expect((await app.inject({ method: "POST", url: "/operator/data-overlays/values/id-1/add", headers, payload: { amount: 1, content: 3 } })).statusCode).toBe(400);
  expect((await app.inject({ method: "POST", url: "/operator/data-overlays/values/missing/reset", headers, payload: {} })).statusCode).toBe(404);
  expect((await app.inject({ method: "POST", url: "/data-overlays/goals", headers, payload: { name: "Missing value", valueId: "missing", mode: "fixed-target", target: 3 } })).statusCode).toBe(400);
  const goal = await app.inject({ method: "POST", url: "/data-overlays/goals", headers, payload: { name: "Target", valueId: "id-1", mode: "saved-baseline", baseline: 0, additionalAmount: 3 } });
  expect(goal.statusCode).toBe(201);
  const deletion = await app.inject({ method: "DELETE", url: "/data-overlays/values/id-1", headers });
  expect(deletion.statusCode).toBe(409); expect(deletion.json().error.references).toContain("goal:id-3");
  const restart = await app.inject({ method: "POST", url: "/operator/data-overlays/goals/id-3/restart", headers, payload: {} });
  expect(restart.statusCode).toBe(200); expect(restart.json().goals[0].baseline).toBe(1);
  expect((await app.inject({ method: "POST", url: "/data-overlays/canvases", headers, payload: { name: "Invalid binding", enabled: false, order: 0, targetProfileId: "landscape", outputs: { browser: true, desktop: false }, elements: [{ id: "bar", kind: "progress", order: 0, x: 0, y: 0, width: 100, height: 50, visible: true, goalId: "missing", orientation: "horizontal", direction: "forward", fillColor: "#ffffffff", backgroundColor: "#000000ff", borderColor: "#000000ff", borderWidthPx: 0 }] } })).statusCode).toBe(400);
  await gate.runMaintenance(async () => { expect((await app.inject({ method: "POST", url: "/operator/data-overlays/values/id-1/reset", headers, payload: {} })).statusCode).toBe(409); });
  await app.close(); db.close();
});
describe("data route binding validation", () => {
  it("rejects a goal over a text value at the domain boundary", () => {
    const db = createInMemoryStreamJamsDatabase(); let id = 0;
    const service = new DataOverlayService(new SqliteDataOverlayRepository(db), { generateId: () => `id-${++id}`, now: () => "2026-10-08T00:00:00.000Z" });
    service.createValue({ name: "Label", kind: "text", resetDefault: "Hello", resetGroupId: null });
    expect(() => service.createGoal({ name: "Goal", valueId: "id-1", mode: "fixed-target", target: 3 })).toThrow();
    expect(service.getState().goals).toEqual([]); db.close();
  });
});
