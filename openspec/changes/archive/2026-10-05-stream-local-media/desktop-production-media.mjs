import { spawn } from 'node:child_process';
import process from 'node:process';
import { mkdir, cp, writeFile, readFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
const root = resolve('apps/desktop/out/media-acceptance');
const source = process.env.STREAM_JAMS_PROBE_ELECTRON ?? 'C:/dev/projects/stream-jams/apps/desktop/node_modules/electron/dist/electron.exe';
await mkdir(root, { recursive: true });
const packaged = resolve(root, 'packaged');
await cp(dirname(source), packaged, { recursive: true });
const appDir = resolve(packaged, 'resources/app'); await mkdir(appDir, { recursive: true });
await cp('openspec/changes/archive/2026-10-05-stream-local-media/desktop-production-media-runtime.mjs', resolve(appDir, 'main.mjs'));
await writeFile(resolve(appDir, 'package.json'), JSON.stringify({ name: 'stream-jams-isolated-production-media', version: '1.0.0', type: 'module', main: 'main.mjs' }));
const runtime = resolve(appDir, 'runtime');
await cp('apps/desktop/dist', resolve(runtime, 'dist'), { recursive: true });
await cp('apps/desktop/src/audio/player.html', resolve(runtime, 'dist/audio/player.html'));
await cp('apps/web/dist-desktop-overlay', resolve(runtime, 'desktop-overlay'), { recursive: true });
await cp('packages/core/dist', resolve(runtime, 'node_modules/@stream-jams/core/dist'), { recursive: true });
await cp('packages/core/package.json', resolve(runtime, 'node_modules/@stream-jams/core/package.json'));
await cp('apps/desktop/node_modules/zod', resolve(runtime, 'node_modules/zod'), { recursive: true, dereference: true });
await writeFile(resolve(runtime, 'package.json'), JSON.stringify({ type: 'module' }));
const exe = resolve(packaged, 'Stream Jams Media Acceptance.exe'); await cp(resolve(packaged, 'electron.exe'), exe);
const env = { ...process.env, STREAM_JAMS_ACCEPTANCE_WORKSPACE: resolve('.'), STREAM_JAMS_ACCEPTANCE_ROOT: root, STREAM_JAMS_ACCEPTANCE_RUNTIME: runtime }; delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(exe, [], { env, windowsHide: true, stdio: 'inherit' });
const code = await new Promise((accept, reject) => { child.once('error', reject); child.once('exit', accept); });
const result = JSON.parse(await readFile(resolve(root, 'results.json'), 'utf8'));
if (result.error) throw new Error(result.error);
process.exitCode = code ?? 1;
